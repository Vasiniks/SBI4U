<p><strong>Real purpose:</strong> regenerate NAD<sup>+</sup> (oxidize NADH) so glycolysis can keep making ATP. Occurs when O<sub>2</sub> is absent or locally depleted. The whole body can't be anaerobic, but parts (working muscle) can.</p>
